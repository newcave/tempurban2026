def classify(text: str) -> dict:
    """반환: cat, label, conf(0~1), severity(1~3), entities, owner, scores, engine"""
    hit = llm.classify_voc(text)          # LLM이 연결돼 있으면 우선
    if hit:
        return hit
    scores = {k: 0.0 for k in C.CAT_KEYS}
    for k, rules in RULES.items():
        for pat, w in rules:
            scores[k] += w * len(re.findall(pat, text))
    tot = sum(scores.values())
    cat = max(scores, key=scores.get) if tot else "amenity"
    conf = scores[cat] / tot if tot else 0.2
    sev = 3 if re.search(SEVERE, text) else 2 if re.search(r"요청|바랍니다|부탁|해 주세요|주세요", text) else 1
    ents = sorted({v for pat, v in ENTITY.items() if re.search(pat, text)})
    return {"cat": cat, "label": C.VOC_CATS[cat]["label"], "conf": round(min(.99, .45 + .55 * conf), 2), "severity": sev,
            "entities": ents, "owner": OWNER[cat], "scores": scores, "engine": "rule"}


