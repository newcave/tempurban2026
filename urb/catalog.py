def ym(t: int) -> str:
    y, m = divmod(T0_MONTH - 1 + int(t), 12)
    return f"{T0_YEAR + y}-{m + 1:02d}"


def t_of(s: str) -> int:
    y, m = map(int, s.split("-")[:2])
    return (y - T0_YEAR) * 12 + (m - T0_MONTH)


